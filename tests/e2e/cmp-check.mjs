import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const p = await (await b.newContext({ viewport: { width: 1024, height: 768 } })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://127.0.0.1:5173/');
await p.waitForSelector('#screen .menu');
await p.click('#screen [data-a=settings]');
await p.waitForSelector('#modal .chip');
const q = await p.textContent('#modal .note');
const m = q.match(/(\d+)\s*\+\s*(\d+)/);
await p.click(`#modal .chip[data-n="${+m[1] + +m[2]}"]`);
await p.waitForSelector('#cmptext');
await p.click('#modal [data-a=cmp-seg]');
await p.waitForTimeout(2500);
const trace = await p.evaluate(() => window.__game.audio.trace);
await p.click('#modal [data-a=cmp-tts]');
await p.waitForTimeout(500);
const traceAfterRaw = await p.evaluate(() => window.__game.audio.trace);
await p.evaluate(() => document.getElementById('cmptext').scrollIntoView());
await p.screenshot({ path: process.argv[2] });
console.log({ trace, rawLeavesTraceUntouched: JSON.stringify(trace) === JSON.stringify(traceAfterRaw), errs });
await b.close();
