import { chromium } from 'playwright-core';
const shot = process.argv[2];
const b = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const p = await (await b.newContext({ viewport: { width: 1024, height: 768 } })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://127.0.0.1:5173/');
await p.waitForSelector('#screen .menu');
await p.click('#screen [data-a=settings]');
await p.waitForSelector('#modal .chip');
const q = await p.textContent('#modal .note');
const [, a, c] = q.match(/(\d+)\s*\+\s*(\d+)/).slice(0, 3).map(Number).length ? q.match(/(\d+)\s*\+\s*(\d+)/) : [];
await p.click(`#modal .chip[data-n="${+a + +c}"]`);
await p.waitForSelector('#modal [data-a=zt]');
const n = await p.$$eval('#modal [data-a=zt]', (e) => e.length);
await p.click('#modal [data-a=zt][data-c="ㄅ"]');
const l1 = await p.textContent('#ztlog');
await p.click('#modal [data-a=ztmode][data-m=word]');
await p.click('#modal [data-a=zt][data-c="ㄆ"]');
const l2 = await p.textContent('#ztlog');
await p.click('#modal [data-a=ztmode][data-m=file]');
await p.click('#modal [data-a=zt][data-c="ㄇ"]');
const l3 = await p.textContent('#ztlog');
await p.evaluate(() => document.querySelector('#modal h3:nth-of-type(3)')?.scrollIntoView());
await p.screenshot({ path: shot });
console.log({ buttons: n, l1, l2, l3, errs });
await b.close();
