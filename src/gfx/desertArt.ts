    sand(c, 56);
    px(c, '#b9824f', 5, 7, 6, 9); px(c, '#9a6a3a', 5, 7, 1, 9); px(c, '#9a6a3a', 10, 7, 1, 9); px(c, '#6e4a2a', 7, 10, 2, 1); px(c, '#6e4a2a', 7, 13, 2, 1);
