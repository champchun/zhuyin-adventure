    px(c, '#5ccf5c', 14, 0, 2, 16); px(c, '#2f9a45', 13, 2, 1, 14); px(c, '#f0c98a', 0, 14, 16, 2); px(c, '#d9a860', 1, 14, 5, 1); px(c, '#d9a860', 9, 15, 5, 1);
