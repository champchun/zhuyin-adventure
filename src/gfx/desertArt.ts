    px(c, '#3fae5a', 6, 2, 4, 14); px(c, '#3fae5a', 2, 6, 4, 3); px(c, '#3fae5a', 2, 4, 2, 3); px(c, '#3fae5a', 11, 4, 3, 4); px(c, '#3fae5a', 12, 2, 2, 3);
    px(c, '#2f8a45', 9, 2, 1, 14); px(c, '#2f8a45', 5, 7, 1, 2); px(c, '#2f8a45', 13, 4, 1, 4);
    px(c, '#bfe89a', 7, 3, 1, 10); px(c, '#ffd84a', 7, 1, 2, 1); px(c, '#ff9db8', 12, 1, 1, 1);
