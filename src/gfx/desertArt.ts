    px(c, '#4a1f1a', 0, 0, 16, 16);
    px(c, '#7a2a1c', 1, 1, 6, 4); px(c, '#7a2a1c', 9, 6, 6, 4); px(c, '#7a2a1c', 2, 10, 5, 5);
    for (const [x, y, w, h] of [[0, 6, 9, 2], [7, 4, 2, 4], [7, 0, 2, 4], [8, 8, 2, 6], [9, 13, 7, 2], [0, 15, 3, 1]]) px(c, '#ff7a1a', x, y, w, h);
