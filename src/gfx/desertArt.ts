    px(c, '#2f6fc0', 0, 10, 16, 6); px(c, '#7fd0ff', 2, 3, 5, 1); px(c, '#7fd0ff', 9, 7, 5, 1); px(c, '#ffffff', 3, 3, 2, 1); px(c, '#ffffff', 10, 7, 2, 1);
